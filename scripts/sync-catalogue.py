#!/usr/bin/env python3
"""Build the catalogue and the function-by-industry matrix.

Reads data/functions.json, data/industries.json and data/extras.json from
this repository, and pmin.json from every repository cloned next to it
(the folder above this one, or --root). Writes catalogue.json,
CATALOGUE.md, MATRIX.md and LAYERING.md here.

A matrix cell is filled when pmin-industries/<industry>/<module>/ exists
under the root (the module's codename, such as lookout).

usage:
  python3 scripts/sync-catalogue.py [--root DIR]          write the files
  python3 scripts/sync-catalogue.py [--root DIR] --check  fail if they are out of date
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TIERS = [
    ("foundation", "Foundation", "The five layers every module builds on, and the only thing a module may use: 1 pmin-base, 2 pmin-sys, 3 pmin-kit, 4 pmin-tools, 5 pmin-contracts."),
    ("function", "Function modules", "One per core function: the primary axis."),
    ("engine", "Engines", "Libraries that each do one job well; a program plugs them into the function modules."),
    ("wrap", "Wrap pipeline", "Describe any command-line program and open it as a form."),
    ("frameworks", "Industry frameworks", "Add-ons to the function modules: specifications, conditions, contexts, rules and variables for each industry."),
    ("program", "Programs", "Assemble the modules into something to run."),
    ("front-door", "Front door", ""),
    ("example", "Built with pmin", "Programs made with these libraries. They are left as they are for now."),
    ("sibling", "Siblings", "Related projects that do not use the libraries."),
    ("empty", "Not started", ""),
    ("legacy", "Legacy", ""),
]


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def gather(root):
    repos = []
    for name in sorted(os.listdir(root)):
        meta = os.path.join(root, name, "pmin.json")
        if os.path.isfile(meta):
            repos.append(load(meta))
    known = {r["name"] for r in repos}
    for e in load(os.path.join(HERE, "data", "extras.json")):
        if e["name"] not in known:
            repos.append(e)
    return repos


def cells(root, functions, industries):
    base = os.path.join(root, "pmin-industries")
    filled = {}
    for ind in industries:
        for fn in functions:
            code = fn["module"].split("-", 1)[1]
            # pmin-scan is the disk engine under Function 7, so a
            # framework's scan places count there.
            codes = [code] + (["scan"] if fn["number"] == 7 else [])
            if any(os.path.isdir(os.path.join(base, ind["slug"], c)) for c in codes):
                filled[(fn["number"], ind["slug"])] = True
    return filled


def catalogue_md(repos, functions):
    out = ["# Catalogue", "", "Generated by `scripts/sync-catalogue.py` from each repository's `pmin.json`. Do not edit by hand.", ""]
    by_tier = {}
    for r in repos:
        by_tier.setdefault(r.get("tier", ""), []).append(r)
    for tier, title, blurb in TIERS:
        rs = by_tier.pop(tier, [])
        if not rs:
            continue
        out += [f"## {title}", ""]
        if blurb:
            out += [blurb, ""]
        if tier == "function":
            out += ["| # | Module | Function | Requires |", "| --- | --- | --- | --- |"]
            for r in sorted(rs, key=lambda r: r["function"]):
                out.append(f"| {r['function']} | {r['name']} | {r['title']} | {', '.join(r.get('requires', [])) or '-'} |")
        else:
            out += ["| Repository | What it is | Requires |", "| --- | --- | --- |"]
            for r in sorted(rs, key=lambda r: r["name"]):
                note = r.get("summary", "")
                if r.get("status") == "planned":
                    note += " *(planned)*"
                out.append(f"| {r['name']} | {note} | {', '.join(r.get('requires', [])) or '-'} |")
        out.append("")
    for tier, rs in by_tier.items():
        out += [f"## {tier or 'Unsorted'}", ""] + [f"- {r['name']}" for r in rs] + [""]
    missing = [f["module"] for f in functions if f["module"] not in {r["name"] for r in repos}]
    if missing:
        out += ["## Missing", "", "Function modules with no pmin.json found: " + ", ".join(missing), ""]
    return "\n".join(out)


MODULE_TIERS = ("function", "engine", "wrap", "frameworks")


def layering_md(repos):
    """The modules that still require another module. Modules use only the
    foundation; programs wire them together. This list should end empty."""
    tier = {r["name"]: r.get("tier") for r in repos}
    out = ["# Layering", "",
           "Modules (function, engine, wrap and frameworks) may use only the foundation: pmin-base, pmin-sys, pmin-kit, pmin-tools and pmin-contracts. Programs wire modules together. This file lists every module that still requires another module; it is written by `scripts/sync-catalogue.py` and should end empty.", ""]
    rows = []
    for r in sorted(repos, key=lambda r: r["name"]):
        if r.get("tier") not in MODULE_TIERS:
            continue
        bad = [d for d in r.get("requires", []) if tier.get(d) != "foundation"]
        if bad:
            rows.append(f"| {r['name']} | {r['tier']} | {', '.join(f'{d} ({tier.get(d)})' for d in bad)} |")
    if not rows:
        out.append("Nothing left: every module uses only the foundation.")
    else:
        out += [f"{len(rows)} module{'s' if len(rows) != 1 else ''} still require another module.", "",
                "| Module | Tier | Still requires |", "|---|---|---|"] + rows
    return "\n".join(out) + "\n"


def matrix_md(functions, industries, filled):
    out = ["# Matrix: 15 functions by 12 industries", "",
           "Generated by `scripts/sync-catalogue.py`. Do not edit by hand.", "",
           "A row is a function module (the primary axis). A column is an industry framework, an add-on to the modules. "
           "● marks a cell that has content in `pmin-industries/<industry>/<module>/` (for Function 7, also `<industry>/scan/`, the disk engine); an empty cell has none yet. "
           "Cells are only created when real content exists.", "",
           "Industries: " + "; ".join(f"**{i['slug']}** = {i['number']}. {i['name']}" for i in industries), ""]
    out.append("| # | Module | " + " | ".join(i["slug"] for i in industries) + " |")
    out.append("| --- | --- | " + " | ".join("---" for _ in industries) + " |")
    for f in functions:
        row = ["●" if filled.get((f["number"], i["slug"])) else " " for i in industries]
        out.append(f"| {f['number']} | {f['module']} | " + " | ".join(row) + " |")
    out += ["", f"Cells with content: {len(filled)} of {len(functions) * len(industries)}.", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=os.path.dirname(HERE), help="folder holding the repositories (default: the one above this)")
    ap.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    a = ap.parse_args()

    functions = load(os.path.join(HERE, "data", "functions.json"))
    industries = load(os.path.join(HERE, "data", "industries.json"))
    if len(functions) != 15 or len(industries) != 12:
        sys.exit("data/: expected 15 functions and 12 industries")
    repos = gather(a.root)
    filled = cells(a.root, functions, industries)

    files = {
        "catalogue.json": json.dumps(sorted(repos, key=lambda r: r["name"]), indent=2, ensure_ascii=False) + "\n",
        "CATALOGUE.md": catalogue_md(repos, functions),
        "MATRIX.md": matrix_md(functions, industries, filled),
        "LAYERING.md": layering_md(repos),
    }
    stale = []
    for name, text in files.items():
        path = os.path.join(HERE, name)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale.append(name)
            if not a.check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
    if a.check and stale:
        sys.exit("out of date: " + ", ".join(stale) + " (run scripts/sync-catalogue.py)")
    print(("up to date" if not stale else "wrote " + ", ".join(stale)) + f": {len(repos)} repositories, {len(filled)} matrix cells")


if __name__ == "__main__":
    main()
